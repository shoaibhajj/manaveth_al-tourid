export function SocialLinks({
  items,
  className = '',
  locale = 'ar',
}: {
  items?: SocialLink[]
  className?: string
  locale?: 'ar' | 'en'
}) {
  if (!items || items.length === 0) return null

  return (
    <div className={`flex flex-wrap items-center gap-2 ${className}`}>
      {items.map((item) => {
        const platform = item.platform || 'other'
        const label = platformLabels[platform]?.[locale] || platformLabels.other[locale]
        return (
          <a
            key={item.url + platform}
            href={item.url}
            target="_blank"
            rel="noopener noreferrer"
            title={label}
            aria-label={label}
            className="flex size-9 items-center justify-center rounded-full border border-gold/30 bg-forest/40 text-cream/80 backdrop-blur-sm transition-all duration-300 hover:-translate-y-0.5 hover:border-gold hover:bg-gold hover:text-forest-deep hover:shadow-[0_0_12px_rgba(212,175,55,0.35)]"
          >
            <SocialIcon platform={platform} />
          </a>
        )
      })}
    </div>
  )
}
